// Compile-only optional LVGL renderer. app_main invokes the marker ONLY.
#include "k151_setup_lvgl.hpp"

namespace stackchan::standalone {
const char* K151SetupLvgl::compiled_link_marker() {
  return "K151 privacy-only LVGL setup screen linked; PANEL NOT STARTED";
}

bool K151SetupLvgl::attach(lv_display_t* display, bool exact_panel_verified,
                           bool lvgl_lock_held, bool trusted_local_owner) {
  if (attempted_ || !display || !exact_panel_verified || !lvgl_lock_held ||
      !trusted_local_owner || stop_.load()) return false;
  attempted_ = true;
  lv_obj_t* screen = lv_display_get_screen_active(display);
  if (!screen) return false;
  root_ = lv_obj_create(screen);
  if (!root_) return false;
  lv_obj_set_size(root_, 300, 180);
  lv_obj_center(root_);
  title_ = lv_label_create(root_);
  first_ = lv_label_create(root_);
  second_ = lv_label_create(root_);
  if (!title_ || !first_ || !second_) {
    (void)detach(true);
    return false;
  }
  lv_obj_align(title_, LV_ALIGN_TOP_MID, 0, 20);
  lv_obj_align(first_, LV_ALIGN_CENTER, 0, 0);
  lv_obj_align(second_, LV_ALIGN_BOTTOM_MID, 0, -24);
  return present(TouchConsentPhase::hold, OwnerSetupPhase::hold,
                 false, false, true);
}

bool K151SetupLvgl::present(TouchConsentPhase touch, OwnerSetupPhase owner,
                            bool trusted_input_ready, bool sensor_read_failed,
                            bool lvgl_lock_held) {
  if (!root_ || !lvgl_lock_held) return false;
  const SetupScreenFrame frame = setup_screen_frame(
      touch, owner, trusted_input_ready, stop_.load(), sensor_read_failed);
  // All three strings are generated by setup_screen_frame() from literals.
  // Never accept, print or render Wi-Fi SSID/password or API token content.
  lv_label_set_text(title_, frame.title);
  lv_label_set_text(first_, frame.line1);
  lv_label_set_text(second_, frame.line2);
  return !stop_.load() && frame.kind != SetupScreenKind::fault;
}

bool K151SetupLvgl::detach(bool lvgl_lock_held) {
  if (!lvgl_lock_held) return false;
  if (root_) lv_obj_delete(root_);
  root_ = title_ = first_ = second_ = nullptr;
  return true;
}
} // namespace stackchan::standalone
