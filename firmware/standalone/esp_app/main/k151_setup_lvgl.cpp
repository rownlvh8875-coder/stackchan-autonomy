const char* K151SetupLvgl::compiled_link_marker() {
  return "K151 privacy-only LVGL setup screen linked; PANEL NOT STARTED";
}

bool K151SetupLvgl::attached() const { return root_ && panel_ && panel_->ready(); }

bool K151SetupLvgl::attach(K151LcdPanel& panel, bool exact_panel_verified,
                           bool lvgl_lock_held, bool trusted_local_owner) {
  if (attempted_ || &panel.stop_ != &stop_ || !panel.ready() ||
      !exact_panel_verified || !lvgl_lock_held ||
      !trusted_local_owner || stop_.load()) return false;
  attempted_ = true;
  panel_ = &panel;
  lv_obj_t* screen = lv_display_get_screen_active(panel.display());
  if (!screen) return false;
  root_ = lv_obj_create(screen);
  if (!root_) return false;
  lv_obj_set_size(root_, 300, 180);
  lv_obj_center(root_);
  title_ = lv_label_create(root_);
  first_ = lv_label_create(root_);
  second_ = lv_label_create(root_);
  if (!title_ || !first_ || !second_) {
    (void)detach(true);
    return false;
  }
  lv_obj_align(title_, LV_ALIGN_TOP_MID, 0, 20);
  lv_obj_align(first_, LV_ALIGN_CENTER, 0, 0);
  lv_obj_align(second_, LV_ALIGN_BOTTOM_MID, 0, -24);
  if (present(TouchConsentPhase::hold, OwnerSetupPhase::hold, false, false, true))
    return true;
  (void)detach(true);
  return false;
}

bool K151SetupLvgl::present(TouchConsentPhase touch, OwnerSetupPhase owner,
                            bool trusted_input_ready, bool sensor_read_failed,
                            bool lvgl_lock_held) {
  if (!attached() || panel_->stop_input_handed_off_ || !lvgl_lock_held) return false;
  sas_visible_ = false;
  if (review_ != ReviewPhase::idle) review_ = ReviewPhase::closed;
  const SetupScreenFrame frame = setup_screen_frame(
      touch, owner, trusted_input_ready, stop_.load(), sensor_read_failed);
  // All three strings are generated by setup_screen_frame() from literals.
  // Never accept, print or render Wi-Fi SSID/password or API token content.
  lv_label_set_text(title_, frame.title);
  lv_label_set_text(first_, frame.line1);
  lv_label_set_text(second_, frame.line2);
  return panel_->present_now() && !stop_.load() && frame.kind != SetupScreenKind::fault;
}

bool K151SetupLvgl::present_pairing_sas(std::string_view code,
                                       bool trusted_display, bool owner_window,
                                       bool lvgl_lock_held) {
  if (review_ != ReviewPhase::idle || !attached() || !trusted_display ||
      !owner_window || !lvgl_lock_held || stop_.load() || code.size()!=8 ||
      !std::all_of(code.begin(),code.end(),
                   [](char c){return c>='0' && c<='9';})) return false;
  std::array<char,9> digits{};
  std::copy(code.begin(),code.end(),digits.begin());
  // The caller must keep the LVGL lock until all changes are complete.
  lv_label_set_text(title_, "USB pairing check");
  lv_label_set_text(first_, digits.data());
  lv_label_set_text(second_, "Compare all 8 digits on your PC");
  sas_visible_ = panel_->present_now() && !stop_.load();
  return sas_visible_;
}

bool K151SetupLvgl::present_saved_setup(SavedSetupScreen screen) {
  if (!attached() || panel_->stop_input_handed_off_ || review_ != ReviewPhase::idle ||
      sas_visible_ || stop_.load()) return false;
  const bool restored = screen == SavedSetupScreen::restored;
  lv_label_set_text(title_, restored ? "SAVED SETUP READY" : "SETUP PRESENCE");
  lv_label_set_text(first_, restored ? "Cloud still OFF" : "Restore saved setup if available");
  lv_label_set_text(second_, restored ? "Review paid voice next" : "Touch top for 3 sec, then lift");
  if (!panel_->present_now() || stop_.load()) return false;
  if (restored) review_ = ReviewPhase::closed;
  else save_after_pairing_ = true;
  return true;
}

bool K151SetupLvgl::add_unlock_label(lv_obj_t* screen, const char* label, int x, int y) {
  if (unlock_labels_count_ == unlock_labels_.size()) return false;
  auto* child = lv_label_create(screen);
  if (!child) return false;
  unlock_labels_[unlock_labels_count_++] = child;
  lv_label_set_text_static(child, label);
  lv_obj_align(child, LV_ALIGN_TOP_MID, x - 160, y);
  return true;
}

bool K151SetupLvgl::present_unlock(UnlockScreen mode, const OwnerCode* generated) {
  if (!attached() || panel_->stop_input_handed_off_ || stop_.load() || sas_visible_ ||
      (mode == UnlockScreen::enroll) != (generated != nullptr)) return false;
  auto* screen = lv_display_get_screen_active(panel_->display());
  if (!screen) return false;
  clear_unlock();
  unlock_screen_ = mode;
  lv_label_set_text_static(title_, "");
  lv_label_set_text_static(first_, "");
  lv_label_set_text_static(second_, "");
  const bool keypad = mode == UnlockScreen::enter;
  const bool deriving = mode == UnlockScreen::deriving;
  const auto caption = keypad ? "Enter your unlock code" : deriving ? "Unlocking setup" :
                                                                    "Write down your unlock code";
  if (!add_unlock_label(screen, caption, 160, 8)) return false;
  if (generated) {
    unlock_input_.set_generated(*generated);
    if (!add_unlock_label(screen, unlock_input_.text(), 160, 92)) return false;
  }
  if (keypad) {
    // Static glyphs and a mask label. No selected character is copied to LVGL.
    static constexpr auto glyphs = [] {
      std::array<std::array<char, 2>, kOwnerCodeAlphabet.size()> result{};
      for (size_t i = 0; i < result.size(); ++i) result[i][0] = kOwnerCodeAlphabet[i];
      return result;
    }();
    if (!add_unlock_label(screen, "", 160, 30)) return false;
    for (size_t i = 0; i < glyphs.size(); ++i) {
      const int x = OwnerCodeInput::kLeft + (static_cast<int>(i % 8) * OwnerCodeInput::kCellWidth)
                    + OwnerCodeInput::kCellWidth / 2;
      const int y = OwnerCodeInput::kTop + (static_cast<int>(i / 8) * OwnerCodeInput::kCellHeight) + 9;
      if (!add_unlock_label(screen, glyphs[i].data(), x, y)) return false;
    }
    if (!add_unlock_label(screen, "Delete", 52, 212)) return false;
  }
  if (!add_unlock_label(screen, "Cancel", 160, 212)) return false;
  if (!deriving && !add_unlock_label(screen, keypad ? "Unlock" : "Saved", 268, 212)) return false;
  return panel_->present_now() && !stop_.load();
}

K151SetupLvgl::UnlockChoice K151SetupLvgl::poll_unlock() {
  uint8_t count{};
  int x{}, y{};
  if (!unlock_screen_ || !attached() || !panel_->read_touch_point(count, x, y))
    return UnlockChoice::fault;
  const bool keypad = *unlock_screen_ == UnlockScreen::enter;
  const int key = unlock_input_.sample(count,
      OwnerCodeInput::key_at(x, y, keypad, *unlock_screen_ == UnlockScreen::deriving));
  if (key == OwnerCodeInput::kCancel) return UnlockChoice::cancel;
  if (key == OwnerCodeInput::kConfirm && unlock_input_.full()) return UnlockChoice::confirm;
  if (keypad && key >= 0 && key <= OwnerCodeInput::kBack) {
    unlock_input_.edit(key);
    std::array<char, kOwnerCodeLength + 1> mask{};
    std::fill_n(mask.begin(), unlock_input_.size(), '*');
    lv_label_set_text(unlock_labels_[1], mask.data());
    if (!panel_->present_now()) return UnlockChoice::fault;
  }
  return UnlockChoice::waiting;
}

void K151SetupLvgl::clear_unlock() {
  for (size_t i = 0; i < unlock_labels_count_; ++i) lv_obj_delete(unlock_labels_[i]);
  unlock_labels_count_ = 0;
  unlock_screen_.reset();
  unlock_input_.clear();
}

bool K151SetupLvgl::finish_unlock(bool restored) {
  clear_unlock();
  if (!attached() || stop_.load()) return false;
  review_ = ReviewPhase::closed;
  lv_label_set_text_static(title_, restored ? "SAVED SETUP READY" : "UNLOCK CODE READY");
  lv_label_set_text_static(first_, "Cloud still OFF");
  lv_label_set_text_static(second_, "Review paid voice next");
  return panel_->present_now() && !stop_.load();
}

bool K151SetupLvgl::begin_pairing_review(uint64_t now, bool lvgl_lock_held) {
  if (review_ != ReviewPhase::idle || !sas_visible_ || !lvgl_lock_held || !attached())
    return false;
  // Keep the displayed SAS visible while the local user compares it.
  lv_label_set_text(title_, "Codes match? Hold screen 1 sec");
  lv_label_set_text(second_, "Then release the screen");
  if (!panel_->present_now() || stop_.load()) return false;
  wait_for_fresh_contact(now);
  return true;
}

K151SetupLvgl::ReviewResult K151SetupLvgl::poll_pairing_review(
    uint64_t now, bool lvgl_lock_held) {
  if (!sas_visible_) return ReviewResult::fault;
  const auto result = poll_contact(now, lvgl_lock_held);
  if (result == ReviewResult::approved && !show_final_touch_prompt())
    return ReviewResult::fault;
  return result;
}

bool K151SetupLvgl::begin_voice_review(uint64_t now, bool allow_first_budget, bool lvgl_lock_held,
                                       bool one_paid_turn,
                                       std::optional<RebootTrialBoot> reboot_trial) {
  if (voice_review_started_ || review_ != ReviewPhase::closed || sas_visible_ ||
      !lvgl_lock_held || !attached()) return false;
  voice_review_started_ = true;
  const char* title = one_paid_turn ? "PAID VOICE (ONE TURN)" : "PAID OPENAI VOICE";
  const char* transmits = allow_first_budget
      ? "Send question audio to OpenAI\nCreate or update NVS budget log"
      : "Send question audio to OpenAI\nUpdate existing NVS budget log";
  const char* confirmation = "Hold screen 1 sec and release";
  if (reboot_trial == RebootTrialBoot::before_reboot) {
    title = "TRIAL: ONE PAID TURN";
  } else if (reboot_trial == RebootTrialBoot::after_reboot) {
    title = "TRIAL: TWO PAID TURNS";
    transmits = "Send question audio to OpenAI\nVerify and update NVS budget";
    confirmation = "Saw Reboot ready?\nHold 1 sec and release";
  }
  lv_label_set_text(title_, title);
  lv_label_set_text(first_, transmits);
  lv_label_set_text(second_, confirmation);
  if (!panel_->present_now() || stop_.load()) return false;
  wait_for_fresh_contact(now);
  return true;
}

K151SetupLvgl::ReviewResult K151SetupLvgl::poll_voice_review(
    uint64_t now, bool lvgl_lock_held) {
  if (!voice_review_started_) return ReviewResult::fault;
  const auto result = poll_contact(now, lvgl_lock_held);
  if (result != ReviewResult::approved) return result;
  lv_label_set_text(title_, "VOICE APPROVED");
  lv_label_set_text(first_, "Starting when ready");
  lv_label_set_text(second_, "Tap the screen to stop");
  voice_approved_ = panel_->present_now() && !stop_.load();
  return voice_approved_ ? ReviewResult::approved : ReviewResult::fault;
}

bool K151SetupLvgl::present_voice_status(K151VoiceStatus status) {
  if (!voice_approved_ || !attached() || !panel_->stop_input_handed_off_) return false;
  if (voice_status_ == status) return !stop_.load();
  const char* text = nullptr;
  switch (status) {
    case K151VoiceStatus::connecting: text = "Connecting to Wi-Fi"; break;
    case K151VoiceStatus::listening: text = "Say Hi StackChan"; break;
    case K151VoiceStatus::question: text = "Say your question"; break;
    case K151VoiceStatus::transcribing: text = "Transcribing question"; break;
    case K151VoiceStatus::generating: text = "Generating answer"; break;
    case K151VoiceStatus::synthesizing: text = "Synthesizing speech"; break;
    case K151VoiceStatus::playing: text = "Playing AI voice"; break;
    case K151VoiceStatus::returning: text = "Returning to standby"; break;
    case K151VoiceStatus::trial_finished: text = "Standby verified. Trial ended."; break;
    case K151VoiceStatus::reboot_ready: text = "Reboot ready. Power off and on."; break;
    case K151VoiceStatus::checking_budget: text = "Checking saved budget"; break;
    case K151VoiceStatus::budget_verified: text = "Previous budget verified"; break;
  }
  if (!text) return false;
  const bool first = !voice_status_;
  if (first) {
    if (status != K151VoiceStatus::connecting &&
        status != K151VoiceStatus::checking_budget) return false;
    lv_label_set_text(title_, "STACKCHAN VOICE");
    lv_label_set_text(second_, "Tap the screen to stop");
  }
  lv_label_set_text_static(first_, text);
  if (!(first ? panel_->present_now() : panel_->present_voice_status_rows()) || stop_.load())
    return false;
  voice_status_ = status;
  return true;
}

void K151SetupLvgl::wait_for_fresh_contact(uint64_t now) {
  last_review_ms_ = now;
  review_ = ReviewPhase::wait_clear;
}

K151SetupLvgl::ReviewResult K151SetupLvgl::poll_contact(
    uint64_t now, bool lvgl_lock_held) {
  uint8_t contacts{};
  if (review_ == ReviewPhase::idle || review_ == ReviewPhase::closed)
    return ReviewResult::fault;
  if (!lvgl_lock_held || !attached() || now < last_review_ms_ ||
      now - last_review_ms_ > kReviewMaxGapMs || !panel_->read_contact_count(contacts)) {
    review_ = ReviewPhase::closed;
    return ReviewResult::fault;
  }
  last_review_ms_ = now;
  if (contacts == 2) {
    review_ = ReviewPhase::wait_clear;
    return ReviewResult::waiting;
  }
  switch (review_) {
    case ReviewPhase::wait_clear:
      if (contacts == 0) review_ = ReviewPhase::wait_press;
      break;
    case ReviewPhase::wait_press:
      if (contacts == 1) {
        hold_since_ms_ = now;
        review_ = ReviewPhase::holding;
      }
      break;
    case ReviewPhase::holding:
      if (contacts == 0) review_ = ReviewPhase::wait_press;
      else if (now - hold_since_ms_ >= kReviewHoldMs) review_ = ReviewPhase::wait_release;
      break;
    case ReviewPhase::wait_release:
      if (contacts == 0) {
        review_ = ReviewPhase::closed;
        return ReviewResult::approved;
      }
      break;
    case ReviewPhase::idle:
    case ReviewPhase::closed:
      return ReviewResult::fault;
  }
  return ReviewResult::waiting;
}

bool K151SetupLvgl::show_final_touch_prompt() {
  sas_visible_ = false;
  lv_label_set_text(title_, "FINAL APPROVAL");
  lv_label_set_text(first_, "Touch top for 3 sec");
  lv_label_set_text(second_, save_after_pairing_ ? "Lift to allow encrypted save" : "Lift to approve");
  return panel_->present_now() && !stop_.load();
}

bool K151SetupLvgl::detach(bool lvgl_lock_held) {
  if (!lvgl_lock_held) return false;
  if (unlock_screen_) {
    clear_unlock();
    if (panel_ && panel_->ready()) (void)panel_->present_now();
  }
  if (root_ && panel_ && panel_->display()) lv_obj_delete(root_);
  root_ = title_ = first_ = second_ = nullptr;
  panel_ = nullptr;
  sas_visible_ = false;
  review_ = ReviewPhase::closed;
  voice_approved_ = false;
  voice_status_.reset();
  return true;
}
